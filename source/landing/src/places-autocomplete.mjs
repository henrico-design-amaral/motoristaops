// Shared progressive enhancement for MotoristaOPS desktop and mobile quote inputs.
// Places API (New), client-side only; never loads a Google script without an enabled
// runtime configuration. No route text is sent to GA4 or to our own server.
const MIN_CHARACTERS = 3;
const DEBOUNCE_MS = 350;
const MAX_PREDICTIONS = 5;
const SAO_PAULO_BIAS = {center:{lat:-23.5505,lng:-46.6333},radius:60000};
const CONFIG_URL = '/assets/places-config.json';

const COPY = {
  pt:{
    privacy:'Sugestões opcionais pelo Google Maps: ao pesquisar, o texto digitado é enviado ao Google. Você também pode preencher manualmente.',
    unavailable:'Sugestões indisponíveis. Digite o endereço manualmente.',
    found:n=>n===1?'1 sugestão de endereço.':' '+n+' sugestões de endereço.',
    select:'Confira o endereço e complemente o ponto de encontro, se necessário.'
  },
  en:{
    privacy:'Optional Google Maps suggestions: what you type is sent to Google when searching. Manual entry is always available.',
    unavailable:'Suggestions unavailable. You can still enter the address manually.',
    found:n=>n===1?'1 address suggestion.':String(n)+' address suggestions.',
    select:'Please check the address and add a meeting point if needed.'
  },
  es:{
    privacy:'Sugerencias opcionales de Google Maps: al buscar, el texto se envía a Google. También puede escribir la dirección manualmente.',
    unavailable:'Sugerencias no disponibles. Puede escribir la dirección manualmente.',
    found:n=>n===1?'1 sugerencia de dirección.':String(n)+' sugerencias de dirección.',
    select:'Verifique la dirección e indique el punto de encuentro, si es necesario.'
  }
};
let mapsLibraryPromise;
let controlSequence=0;

export function isValidPlacesConfig(value) {
  return value?.enabled===true && typeof value.browserKey==='string'
    && /^AIza[0-9A-Za-z_-]{30,}$/.test(value.browserKey);
}

// This file is generated by build.mjs. It is public browser configuration;
// never place a server credential or an unrestricted API key in it.
export async function readPlacesConfig(fetcher=globalThis.fetch) {
  if (typeof fetcher!=='function') return null;
  try {
    const response=await fetcher(CONFIG_URL,{cache:'no-store',credentials:'same-origin'});
    if (!response?.ok) return null;
    const config=await response.json();
    return isValidPlacesConfig(config) ? {enabled:true,browserKey:config.browserKey} : null;
  } catch {
    return null; // An unavailable configuration must not break manual entry.
  }
}

export function selectionText(predictionText, formattedAddress, maxLength=220) {
  const clean=value=>String(value||'').replace(/\s+/g,' ').trim();
  const prediction=clean(predictionText), address=clean(formattedAddress);
  const limit=Number.isInteger(maxLength)&&maxLength>0?maxLength:220;
  const chosen=prediction.length<=limit ? prediction : (address.length<=limit ? address : prediction);
  return (chosen || address).slice(0,limit).trim();
}

function languageCode(locale) {
  if (String(locale).toLowerCase().startsWith('en')) return 'en';
  if (String(locale).toLowerCase().startsWith('es')) return 'es';
  return 'pt';
}

function googleLanguage(locale) {
  return {pt:'pt-BR',en:'en',es:'es'}[languageCode(locale)];
}

// A single loader is reused for both fields. Script URL deliberately contains
// only a referrer-restricted *browser key*, never a server secret.
export function loadPlacesLibrary(config,locale='pt') {
  if (!isValidPlacesConfig(config)) return Promise.reject(new Error('Places disabled'));
  if (globalThis.google?.maps?.importLibrary) return globalThis.google.maps.importLibrary('places');
  if (!mapsLibraryPromise) {
    mapsLibraryPromise=new Promise((resolve,reject)=>{
      const callback='__mopsPlacesGoogleReady';
      const script=document.createElement('script');
      const params=new URLSearchParams({
        key:config.browserKey,v:'weekly',libraries:'places',loading:'async',
        language:googleLanguage(locale),region:'BR',callback
      });
      let done=false;
      const timeout=setTimeout(()=>finish(new Error('Maps loading timeout')),12000);
      const finish=(error)=>{
        if(done)return;
        done=true;
        clearTimeout(timeout);
        try{delete globalThis[callback];}catch{}
        if(error){script.remove();reject(error);return;}
        if(!globalThis.google?.maps?.importLibrary){
          reject(new Error('Maps library unavailable'));return;
        }
        resolve(globalThis.google.maps.importLibrary('places'));
      };
      globalThis[callback]=()=>finish(null);
      script.async=true;
      script.referrerPolicy='strict-origin-when-cross-origin';
      script.src='https://maps.googleapis.com/maps/api/js?'+params.toString();
      script.addEventListener('error',()=>finish(new Error('Google Maps not reachable')),{once:true});
      document.head.appendChild(script);
    }).catch(error=>{mapsLibraryPromise=null;throw error;});
  }
  return mapsLibraryPromise;
}

function plainPredictionText(prediction) {
  return typeof prediction?.text?.toString==='function'
    ? String(prediction.text.toString()).trim() : '';
}

export function attachPlacesField({input,mount,locale='pt',config,onSelect=()=>{},loader=loadPlacesLibrary,showPrivacy=true}) {
  if (!input || !mount || !isValidPlacesConfig(config)) return ()=>{};
  const t=COPY[languageCode(locale)];
  const id='mops-place-list-'+(++controlSequence);
  const previous=new Map(['role','aria-autocomplete','aria-controls','aria-expanded','aria-activedescendant','autocomplete']
    .map(name=>[name,input.getAttribute(name)]));
  input.setAttribute('role','combobox');
  input.setAttribute('aria-autocomplete','list');
  input.setAttribute('aria-controls',id);
  input.setAttribute('aria-expanded','false');
  input.setAttribute('autocomplete','off');

  const box=document.createElement('div');
  box.className='mops-places-results';
  box.id=id;
  box.setAttribute('role','listbox');
  box.hidden=true;
  const live=document.createElement('span');
  live.className='sr-only mops-places-live';
  live.setAttribute('role','status');
  live.setAttribute('aria-live','polite');
  const notice=document.createElement('p');
  notice.className='mops-places-privacy';
  notice.textContent=t.privacy;
  notice.hidden=!showPrivacy;
  mount.append(box,live,notice);

  let destroyed=false,querySequence=0,timer=null,token=null,options=[],active=-1,composing=false,applying=false;

  function close() {
    box.hidden=true;
    box.replaceChildren();
    options=[];
    active=-1;
    input.setAttribute('aria-expanded','false');
    input.removeAttribute('aria-activedescendant');
  }
  function invalidatePending() {
    querySequence++;
    if(timer!==null){clearTimeout(timer);timer=null;}
    close();
  }
  function highlight() {
    for(let i=0;i<options.length;i++){
      const row=box.querySelector('[data-place-index="'+i+'"]');
      if(row)row.setAttribute('aria-selected',String(i===active));
    }
    if(active>=0)input.setAttribute('aria-activedescendant',id+'-opt-'+active);
    else input.removeAttribute('aria-activedescendant');
  }
  async function choose(prediction) {
    if(destroyed)return;
    invalidatePending();
    const selectionVersion=querySequence;
    // Discard this field's billing token after selection; a new edit starts a new session.
    token=null;
    const original=plainPredictionText(prediction);
    let address='';
    try {
      const place=prediction.toPlace();
      // formattedAddress is an Essentials field; avoid Pro/Enterprise fields.
      await place.fetchFields({fields:['formattedAddress']});
      address=place.formattedAddress||'';
    } catch {
      // The user-selected prediction is still usable as manually editable text.
    }
    if(destroyed || selectionVersion!==querySequence)return;
    const next=selectionText(original,address,input.maxLength);
    if(!next)return;
    applying=true;
    input.value=next;
    input.dispatchEvent(new Event('input',{bubbles:true}));
    input.dispatchEvent(new Event('change',{bubbles:true}));
    applying=false;
    onSelect(input.name,next);
    live.textContent=t.select;
    close();
    input.focus({preventScroll:true});
  }
  function show(predictions) {
    close();
    const actual=predictions.slice(0,MAX_PREDICTIONS).filter(Boolean);
    if(!actual.length)return;
    for(const [index,prediction] of actual.entries()){
      const row=document.createElement('div');
      row.className='mops-places-option';
      row.setAttribute('role','option');
      row.id=id+'-opt-'+index;
      row.dataset.placeIndex=String(index);
      row.setAttribute('aria-selected','false');
      row.textContent=plainPredictionText(prediction);
      let handledByPointer=false;
      row.addEventListener('pointerdown',event=>{
        event.preventDefault(); // Keep input focus during touch/mouse selection.
        handledByPointer=true;
        void choose(prediction);
      });
      row.addEventListener('click',()=>{if(!handledByPointer)void choose(prediction);});
      box.appendChild(row);
    }
    const attribution=document.createElement('div');
    attribution.className='mops-places-attribution';
    const google=document.createElement('span');
    google.className='mops-places-google';
    google.textContent='Google Maps';
    google.setAttribute('translate','no');
    attribution.appendChild(google);
    box.appendChild(attribution);
    options=actual;
    box.hidden=false;
    input.setAttribute('aria-expanded','true');
    live.textContent=t.found(actual.length).trim();
  }
  function onInput(){
    invalidatePending();
    if(applying)return;
    if(composing)return;
    const q=input.value.trim();
    if(q.length<MIN_CHARACTERS){token=null;return;}
    const version=querySequence;
    timer=setTimeout(async()=>{
      timer=null;
      try {
        const places=await loader(config,locale);
        if(destroyed || querySequence!==version || input.value.trim()!==q)return;
        if(!token)token=new places.AutocompleteSessionToken();
        const result=await places.AutocompleteSuggestion.fetchAutocompleteSuggestions({
          input:q,sessionToken:token,language:googleLanguage(locale),
          region:'br',locationBias:SAO_PAULO_BIAS
        });
        if(destroyed || querySequence!==version || input.value.trim()!==q)return;
        show((result?.suggestions||[]).map(item=>item.placePrediction).filter(Boolean));
      } catch {
        if(!destroyed && querySequence===version) {
          close();
          live.textContent=t.unavailable;
          token=null;
        }
      }
    },DEBOUNCE_MS);
  }
  function onKey(event) {
    if(box.hidden)return;
    if(event.key==='Escape'){event.preventDefault();close();return;}
    if(event.key==='ArrowDown'||event.key==='ArrowUp'){
      event.preventDefault();
      active=event.key==='ArrowDown'
        ?(active+1)%options.length
        :(active<0?options.length-1:(active+options.length-1)%options.length);
      highlight();
      return;
    }
    if(event.key==='Enter'&&active>=0){
      event.preventDefault();
      void choose(options[active]);
    }
  }
  function onOutside(event) {
    if(event.target!==input && !mount.contains(event.target))close();
  }
  function onBlur(){
    // Pointer selection prevents blur; a real Tab-out closes predictions.
    setTimeout(()=>{if(!destroyed && document.activeElement!==input)close();},100);
  }
  function onCompositionStart(){composing=true;invalidatePending();}
  function onCompositionEnd(){composing=false;onInput();}
  input.addEventListener('input',onInput);
  input.addEventListener('keydown',onKey);
  input.addEventListener('blur',onBlur);
  input.addEventListener('compositionstart',onCompositionStart);
  input.addEventListener('compositionend',onCompositionEnd);
  document.addEventListener('pointerdown',onOutside,true);
  return ()=>{
    destroyed=true;
    invalidatePending();
    input.removeEventListener('input',onInput);
    input.removeEventListener('keydown',onKey);
    input.removeEventListener('blur',onBlur);
    input.removeEventListener('compositionstart',onCompositionStart);
    input.removeEventListener('compositionend',onCompositionEnd);
    document.removeEventListener('pointerdown',onOutside,true);
    for(const [name,value] of previous){
      if(value===null)input.removeAttribute(name);else input.setAttribute(name,value);
    }
    box.remove();
    live.remove();
    notice.remove();
  };
}

export async function enhancePlacesFields(fields,{locale='pt',onSelect=()=>{},readConfig=readPlacesConfig,loader=loadPlacesLibrary}={}) {
  const config=await readConfig();
  if(!config)return()=>{};
  const cleanups=fields.map((field,index)=>attachPlacesField({...field,locale,config,onSelect,loader,showPrivacy:index===0}));
  return ()=>cleanups.forEach(dispose=>dispose());
}
